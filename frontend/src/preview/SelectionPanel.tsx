import { useMemo } from "react";
import type { WireEnd, WireInfo } from "../api/client";
import { locateComponent, type Location } from "../editor/locate";
import type { Selection } from "./selection";

// Info about the selected connector, cable or wire (SPEC FR-31). Line links jump the editor.
export function SelectionPanel({
  selection,
  yamlText,
  wires,
  onReveal,
  onSelect,
}: {
  selection: Selection;
  yamlText: string;
  wires: Record<string, WireInfo>;
  onReveal: (line: number) => void;
  onSelect: (selection: Selection | null) => void;
}) {
  const wire = selection.kind === "wire" ? wires[selection.key] : undefined;
  const designator = selection.kind === "component" ? selection.designator : wire?.cable;
  const located = useMemo(
    () => (designator ? locateComponent(yamlText, designator) : null),
    [yamlText, designator],
  );

  const endButton = (end: WireEnd | null) =>
    end ? (
      <button
        className="link"
        onClick={() => onSelect({ kind: "component", designator: end.connector })}
        title="Select this connector"
      >
        {displayName(end.connector)}:{end.pin}
        {end.label ? ` (${end.label})` : ""}
      </button>
    ) : (
      <span className="muted">not connected</span>
    );

  return (
    <aside className="selection" aria-label="Selection">
      <div className="selection-header">
        {wire ? (
          <strong>
            {wire.cable} wire {wire.wire}
          </strong>
        ) : (
          <strong>{designator ? displayName(designator) : "?"}</strong>
        )}
        {located?.section && (
          <span className="muted">{located.section === "cables" ? "cable" : "connector"}</span>
        )}
        {located?.generatedFrom && (
          <span className="muted">generated by WireViz from {located.generatedFrom}</span>
        )}
        <button className="close" onClick={() => onSelect(null)} aria-label="Clear selection">
          ×
        </button>
      </div>

      {wire && (
        <div className="wire-summary">
          {[wire.color, wire.gauge, wire.length].filter(Boolean).join(" · ")}
          <div>
            {endButton(wire.from)} → {endButton(wire.to)}
          </div>
        </div>
      )}

      {located?.definition && (
        <LocationLink label="Defined" location={located.definition} onReveal={onReveal} />
      )}
      {located?.usages.map((usage, i) => (
        <LocationLink key={`${usage.line}-${i}`} label="Used" location={usage} onReveal={onReveal} />
      ))}
      {located && !located.definition && located.usages.length === 0 && (
        <p className="muted">Not found in the editor text (it may have changed since the last render).</p>
      )}

      {located?.attributes && !wire && (
        <table className="attributes">
          <tbody>
            {Object.entries(located.attributes).map(([key, value]) => (
              <tr key={key}>
                <th>{key}</th>
                <td>{format(value)}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
    </aside>
  );
}

function LocationLink({
  label,
  location,
  onReveal,
}: {
  label: string;
  location: Location;
  onReveal: (line: number) => void;
}) {
  return (
    <button className="location" onClick={() => onReveal(location.line)}>
      <span className="muted">
        {label}, line {location.line}:
      </span>{" "}
      <code>{location.text}</code>
    </button>
  );
}

function displayName(designator: string): string {
  return /^__(.+)_(\d+)$/.test(designator) ? designator.replace(/^__(.+)_(\d+)$/, "$1 #$2") : designator;
}

function format(value: unknown): string {
  if (Array.isArray(value)) return value.map(format).join(", ");
  if (value && typeof value === "object") return JSON.stringify(value);
  return String(value);
}
